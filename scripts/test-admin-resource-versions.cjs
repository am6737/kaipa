const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
// Run the pure TypeScript state transitions without an Expo/browser runtime.
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, filename);
const { resourceSnapshot, resourceRelease, saveResourceDraft, publishResource, discardResourceDraft, rollbackResource, resourceDiff } = require('../src/web/admin/resourceVersions.ts');
const date = '2026-09-07 12:00:00';
const original = { id: 'R-test', name: '原路线', detail: '原简介', owner: '编辑部', category: '入门', status: '已发布', date, image: 'old.png', fields: { region: '浙江', distance: '8' }, routeStops: [{ id: 's1', name: '起点', note: '' }] };
const originalJSON = JSON.stringify(original);
const changed = { ...resourceSnapshot(original), name: '新路线', image: '', routeStops: [{ id: 's2', name: '终点', note: '补水' }] };
const draft = saveResourceDraft(original, changed, 0, date);
assert.equal(draft.name, '原路线');
assert.equal(draft.image, 'old.png');
assert.equal(draft.release.draft.name, '新路线');
changed.routeStops[0].name = '外部修改';
assert.equal(draft.release.draft.routeStops[0].name, '终点');
assert.throws(() => saveResourceDraft(draft, changed, 0, date), /变化/);
assert.throws(() => publishResource(draft, 'routes', 1, '', date), /发布说明/);
assert.throws(() => rollbackResource(draft, 1, 1, '原因', date), /草稿/);
const published = publishResource(draft, 'routes', 1, '更新路线', date);
assert.equal(published.name, '新路线');
assert.equal(published.image, '');
assert.equal(published.release.draft, undefined);
assert.equal(published.release.versions.length, 2);
assert.equal(published.release.versions[0].snapshot.name, '原路线');
const restored = rollbackResource(published, 1, 2, '恢复旧路线', date);
assert.equal(restored.name, '原路线');
assert.equal(restored.image, 'old.png');
assert.equal(restored.release.versions.length, 3);
assert.equal(restored.release.versions[2].number, 3);
assert.equal(restored.release.versions[2].restoredFrom, 1);
assert.equal(published.release.versions.length, 2);
assert.throws(() => rollbackResource({ ...published, status: '已下架' }, 1, 2, '原因', date), /下架/);
assert.throws(() => rollbackResource(published, 2, 2, '原因', date), /历史/);
assert.throws(() => rollbackResource(published, 999, 2, '原因', date), /历史/);
const discarded = discardResourceDraft(draft, 1, date);
assert.equal(discarded.name, '原路线');
assert.equal(discarded.release.draft, undefined);
assert.equal(discarded.release.versions.length, 1);
const identicalDraft = saveResourceDraft(published, resourceSnapshot(published), 2, date);
assert.throws(() => publishResource(identicalDraft, 'routes', 3, '无内容变化', date), /一致/);
const first = { ...original, status: '草稿' };
assert.equal(resourceRelease(first).versions.length, 0);
assert.throws(() => discardResourceDraft(first, 0, date), /首次/);
assert.equal(publishResource(first, 'routes', 0, '首次上线', date).release.versions[0].number, 1);
const invalid = saveResourceDraft(first, { ...resourceSnapshot(first), fields: { distance: '-5', region: '' } }, 0, date);
assert.throws(() => publishResource(invalid, 'routes', 1, '上线', date), /不能为空/);
assert.equal(JSON.stringify(original), originalJSON);
const items = [{ id: 'a', name: '帐篷', category: '睡眠', quantity: 1, weightGrams: 800, required: true }, { id: 'b', name: '睡袋', category: '睡眠', quantity: 2, weightGrams: null, required: false }];
const template = { ...resourceSnapshot(original), checklistItems: items };
assert.equal(resourceDiff(template, { ...template, checklistItems: [...items].reverse() }, {}).some(item => item.key === 'items'), true);
assert.equal(resourceDiff(template, { ...template, checklistItems: items.map(item => ({ ...item, quantity: 3 })) }, {}).some(item => item.key === 'items'), true);
assert.equal(resourceDiff(original, { ...resourceSnapshot(original), image: '' }, {}).some(item => item.image), true);
console.log('PASS: live/draft isolation, immutable snapshots, first publish, revisions, publish validation, no-op rejection, discard, rollback append-only, offline guard, diff arrays/images.');
