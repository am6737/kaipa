#!/usr/bin/env node
// generate-route-seasons.mjs — emit the route best-season migration.
//
// Reads the hand-curated scripts/route-seasons.json (stem -> months + note)
// and matches it against the id/name pairs already written by
// import-hiking-routes.mjs, then writes a migration that adds the
// best_months / season_note columns (idempotent) and fills them per route.
//
// Usage:
//   node scripts/generate-route-seasons.mjs [out-sql]

import fs from 'node:fs';
import path from 'node:path';

const SEASONS_FILE = path.join(path.dirname(new URL(import.meta.url).pathname), 'route-seasons.json');
const IMPORT_SQL = 'supabase/migrations/20260917140000_import_hiking_routes.sql';
const OUT_SQL = process.argv[2] ?? 'supabase/migrations/20260917180000_route_seasons.sql';

const seasons = JSON.parse(fs.readFileSync(SEASONS_FILE, 'utf8'));

// Pull the id/name pairs out of the import migration's insert values so the
// stem keys never have to carry trk ids themselves.
const sqlText = fs.readFileSync(IMPORT_SQL, 'utf8');
const rows = [...sqlText.matchAll(/\('(trk\d+)', '([^']+)',/g)].map((m) => ({ id: m[1], name: m[2] }));

const byName = new Map(rows.map((r) => [r.name, r.id]));
const problems = [];
const updates = [];
for (const [stem, entry] of Object.entries(seasons)) {
  const id = byName.get(stem);
  if (!id) {
    problems.push(`no imported route matches stem: ${stem}`);
    continue;
  }
  if (!Array.isArray(entry.months) || entry.months.length === 0) {
    problems.push(`${stem}: months must be a non-empty array`);
    continue;
  }
  for (const m of entry.months) {
    if (!Number.isInteger(m) || m < 1 || m > 12) {
      problems.push(`${stem}: invalid month ${m}`);
    }
  }
  const months = `{${entry.months.join(',')}}`;
  const note = entry.note ? `, season_note = '${entry.note.replace(/'/g, "''")}'` : ', season_note = null';
  updates.push(`update routes set best_months = '${months}'${note} where id = '${id}';`);
}
for (const row of rows) {
  if (!seasons[row.name]) problems.push(`imported route has no season entry: ${row.name} (${row.id})`);
}

if (problems.length) {
  for (const p of problems) console.error(`ERROR ${p}`);
  process.exit(1);
}

const sql = `-- Fill imported routes with best-season metadata (best_months + season_note).
--
-- Hand-curated in scripts/route-seasons.json; this migration is generated by
-- scripts/generate-route-seasons.mjs on ${new Date().toISOString().slice(0, 10)}.
-- Regenerate with:
--   node scripts/generate-route-seasons.mjs
--
-- Effect:
--   1. adds the season columns to routes (idempotent)
--   2. fills them for every imported route

do $$ begin
  if not exists (select 1 from information_schema.columns where table_schema='public' and table_name='routes' and column_name='best_months') then
    alter table routes add column best_months int4[];
  end if;
  if not exists (select 1 from information_schema.columns where table_schema='public' and table_name='routes' and column_name='season_note') then
    alter table routes add column season_note text;
  end if;
end $$;

${updates.join('\n')}
`;
fs.mkdirSync(path.dirname(OUT_SQL), { recursive: true });
fs.writeFileSync(OUT_SQL, sql);

console.log(`Wrote ${updates.length} season updates -> ${OUT_SQL}`);
