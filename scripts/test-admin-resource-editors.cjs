const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(process.env.ADMIN_MOCK_URL || 'http://localhost:8092/admin-preview.html');
    await page.locator('h1').waitFor();
    const nav = async name => {
      await page.getByRole('navigation', { name: '后台导航' }).getByRole('button', { name, exact: true }).click();
      await page.getByRole('heading', { name, exact: true }).waitFor();
    };
    const close = () => page.getByRole('button', { name: '关闭详情', exact: true }).click();
    const edit = () => page.getByRole('button', { name: '编辑', exact: true }).click();
    const save = () => page.getByRole('button', { name: '保存修改', exact: true }).click();

    await nav('路线资源');
    await page.getByRole('button', { name: '莫干山竹林环线', exact: true }).click();
    await edit();
    assert.equal(await page.getByLabel('累计爬升（m）').inputValue(), '420');
    await page.getByLabel('预计时长（小时）').fill('4.5');
    await page.getByLabel('出行提醒').fill('雨天注意湿滑路段，提前确认返程交通。');
    await page.getByRole('button', { name: '添加途经点', exact: true }).click();
    await page.getByLabel('途经点 1 名称').fill('竹林入口');
    await page.getByLabel('途经点 1 备注').fill('停车与补水');
    await page.getByRole('button', { name: '添加途经点', exact: true }).click();
    await page.getByLabel('途经点 2 名称').fill('观景平台');
    await page.getByRole('button', { name: '上移途经点 2', exact: true }).click();
    assert.equal(await page.getByLabel('途经点 1 名称').inputValue(), '观景平台');
    await page.getByRole('button', { name: '选择森林封面', exact: true }).click();
    await page.getByLabel('上传图片').setInputFiles({ name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('bad image') });
    assert.match(await page.getByRole('alert').innerText(), /2 MB/);
    await page.locator('.drawer').evaluate(element => element.scrollTo(0, 0));
    await page.screenshot({ path: '/tmp/kaipa-resource-route-editor.png' });
    await save();
    await page.getByRole('button', { name: '莫干山竹林环线', exact: true }).click();
    assert.match(await page.getByRole('dialog').innerText(), /观景平台/);
    await edit();
    assert.equal(await page.getByLabel('预计时长（小时）').inputValue(), '4.5');
    await page.getByLabel('距离（km）').fill('-1');
    await save();
    assert.equal(await page.getByLabel('距离（km）').getAttribute('aria-invalid'), 'true');
    page.once('dialog', dialog => dialog.dismiss());
    await close();
    assert.equal(await page.getByRole('dialog').count(), 1);
    page.once('dialog', dialog => dialog.accept());
    await close();
    await page.getByRole('button', { name: '武功山经典穿越', exact: true }).click();
    await page.getByRole('button', { name: '复制为草稿', exact: true }).click();
    await page.getByRole('button', { name: '保存草稿', exact: true }).click();
    assert.match(await page.locator('tbody tr').filter({ hasText: '武功山经典穿越（副本）' }).innerText(), /草稿/);
    assert.match(await page.locator('tbody tr').filter({ has: page.getByRole('button', { name: '武功山经典穿越', exact: true }) }).innerText(), /已发布/);

    await nav('公共装备库');
    await page.getByRole('button', { name: '钛合金套锅', exact: true }).click();
    await edit();
    await page.getByLabel('型号', { exact: true }).fill('Ti-750');
    await page.getByLabel('材质', { exact: true }).fill('纯钛');
    await page.getByLabel('容量', { exact: true }).fill('750 mL');
    await page.getByLabel('参考价（元）').fill('299');
    await page.getByLabel('重量（g）').fill('180');
    await page.getByLabel('上传图片').setInputFiles(path.join(__dirname, '../assets/icon.png'));
    await page.waitForFunction(() => document.querySelector('.resource-cover')?.getAttribute('src')?.startsWith('data:image/'));
    await save();
    await page.getByRole('button', { name: '钛合金套锅', exact: true }).click();
    assert.match(await page.getByRole('dialog').innerText(), /Ti-750/);
    await edit();
    assert.equal(await page.getByLabel('重量（g）').inputValue(), '180');
    await page.getByRole('button', { name: '移除图片', exact: true }).click();
    await save();

    await nav('清单模板');
    await page.getByRole('button', { name: '新建模板', exact: true }).click();
    await page.getByLabel(/^名称/).fill('周末测试清单');
    await page.getByLabel(/^简介/).fill('轻量周末出行');
    await page.getByRole('button', { name: '保存草稿', exact: true }).click();
    assert.match(await page.getByRole('alert').innerText(), /至少添加一项/);
    await page.getByLabel('选择公共装备').selectOption('G-101');
    await page.getByRole('button', { name: '添加', exact: true }).click();
    await page.getByLabel('条目 1 数量').fill('2');
    await page.getByRole('button', { name: '自定义条目', exact: true }).click();
    await page.getByLabel('条目 2 名称').fill('饮用水');
    assert.match(await page.locator('.checklist-editor .packing-totals').innerText(), /1 项重量未填写/);
    await page.getByLabel('条目 2 重量').fill('1000');
    assert.match(await page.locator('.checklist-editor .packing-totals').innerText(), /2.96 kg/);
    await page.getByRole('button', { name: '上移条目 2', exact: true }).click();
    assert.equal(await page.getByLabel('条目 1 名称').inputValue(), '饮用水');
    await page.getByRole('button', { name: '删除条目 1', exact: true }).click();
    await page.getByLabel('条目 1 名称').fill('我的徒步背包');
    await page.getByRole('button', { name: '撤销最近一次删除', exact: true }).click();
    assert.equal(await page.getByLabel('条目 1 名称').inputValue(), '饮用水');
    assert.equal(await page.getByLabel('条目 2 名称').inputValue(), '我的徒步背包');
    await page.getByLabel('条目 1 数量').fill('1.5');
    await page.getByRole('button', { name: '保存草稿', exact: true }).click();
    assert.match(await page.getByRole('alert').innerText(), /数量/);
    await page.getByLabel('条目 1 数量').fill('1');
    await page.getByRole('button', { name: '选择山地封面', exact: true }).click();
    await page.locator('.drawer').evaluate(element => element.scrollTo(0, 0));
    await page.screenshot({ path: '/tmp/kaipa-resource-checklist-editor.png' });
    await page.getByRole('button', { name: '保存草稿', exact: true }).click();
    await page.getByRole('button', { name: '周末测试清单', exact: true }).click();
    assert.match(await page.getByRole('dialog').innerText(), /2.96 kg/);
    await edit();
    assert.equal(await page.getByLabel('条目 1 名称').inputValue(), '饮用水');
    await page.getByRole('button', { name: '预览', exact: true }).click();
    assert.equal(await page.locator('.resource-preview').isVisible(), true);
    await page.screenshot({ path: '/tmp/kaipa-resource-preview.png' });
    await close();
    await page.getByRole('button', { name: '切换主题' }).click();
    await page.getByRole('button', { name: '周末测试清单', exact: true }).click();
    await edit();
    await page.screenshot({ path: '/tmp/kaipa-resource-editor-dark.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: '/tmp/kaipa-resource-editor-mobile-dark.png' });
    assert.equal(await page.locator('.drawer').evaluate(element => element.clientWidth === element.scrollWidth), true);
    await page.getByRole('button', { name: '预览', exact: true }).click();
    await page.screenshot({ path: '/tmp/kaipa-resource-preview-mobile.png' });
    await close();
    await page.getByRole('button', { name: '切换主题' }).click();
    await page.getByRole('button', { name: '周末测试清单', exact: true }).click();
    await edit();
    await page.screenshot({ path: '/tmp/kaipa-resource-editor-mobile.png' });
    assert.equal(await page.locator('.drawer').evaluate(element => element.clientWidth === element.scrollWidth), true);
    assert.deepEqual(errors, []);
    console.log('PASS: route stops, image validation, route roundtrip, unsaved guard, duplicate isolation, gear specs/upload/removal, checklist add/reorder/delete/undo/weights/validation/roundtrip, preview, desktop/mobile/light/dark.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
