const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, filename);
const { applyTaskBatch, batchSkipReason } = require('../src/web/admin/taskBatchModel.ts');
const date = '2026-09-07 10:00:00';
const records = { admins: [{ id: 'A', name: 'Admin', category: '超级管理员', status: '正常' }, { id: 'B', name: 'Ops', category: '运营管理员', status: '正常' }, { id: 'C', name: 'Guest', status: '邀请中' }], reports: [{ id: 'R1', status: '待处理' }, { id: 'R2', status: '处理中' }, { id: 'R3', status: '已处理' }] };
const first = { id: 'T1', title: '待办一', assignee: 'A', collaborators: ['B'], kind: 'report', target: { section: 'reports', id: 'R1' }, priority: '高', due: '2026-09-06 10:00' };
const tasks = [first, { ...first, id: 'T2', assignee: 'B', collaborators: ['A'], target: { section: 'reports', id: 'R2' } }, { ...first, id: 'T3', target: { section: 'reports', id: 'R3' } }];
const original = JSON.stringify({ tasks, records });
const picks = tasks.map(task => ({ id: task.id, revision: 0 }));
let sequence = 0;
const run = (values, command, at = date) => applyTaskBatch(values, command, records, 'A', at, () => `id-${sequence++}`);
const assign = { kind: 'assign', assignee: 'B', picks, text: '统一转交运营处理' };
const result = run(tasks, assign);
assert.equal(result.changed.length, 1);
assert.deepEqual(result.skipped.map(item => item.reason), ['负责人未变化', '任务已完成']);
assert.deepEqual(result.tasks[0].collaborators, []);
assert.equal(result.tasks[0].due, first.due);
assert.equal(result.tasks[0].priority, first.priority);
assert.deepEqual(result.notices.map(notice => notice.recipient), ['B']);
assert.equal(JSON.stringify({ tasks, records }), original);
assert.throws(() => run(tasks, { ...assign, text: ' ' }), /说明/);
assert.throws(() => run(tasks, { ...assign, assignee: 'C' }), /正常/);
assert.throws(() => run(tasks, { ...assign, picks: [...picks, picks[0]] }), /不重复/);
assert.throws(() => run(tasks, { ...assign, picks: [picks[0], { ...picks[1], revision: 3 }] }), /任务已变化/);
assert.equal(JSON.stringify({ tasks, records }), original);
const remind = { kind: 'remind', picks, text: '请更新逾期事项进展' };
const reminded = run(tasks, remind);
assert.equal(reminded.changed.length, 2);
assert.deepEqual(reminded.notices.map(notice => notice.recipient), ['A', 'B']);
assert.equal(reminded.tasks[0].events[0].kind, 'reminder');
const newPicks = reminded.tasks.map(task => ({ id: task.id, revision: task.revision ?? 0 }));
assert.throws(() => run(reminded.tasks, { ...remind, picks: newPicks }), /没有可执行/);
assert.equal(run(reminded.tasks, { ...remind, picks: newPicks }, '2026-09-08 10:00:00').changed.length, 2);
const timestamp = Date.parse('2026-09-07T10:00:00Z');
assert.equal(batchSkipReason({ ...first, due: '2026-09-07 10:00' }, 'remind', '', records, timestamp), '尚未逾期');
assert.equal(batchSkipReason({ ...first, assignee: '' }, 'remind', '', records, timestamp), '尚未分配负责人');
assert.equal(batchSkipReason({ ...first, assignee: 'C' }, 'remind', '', records, timestamp), '负责人不可接收提醒');
assert.equal(batchSkipReason({ ...first, target: { section: 'reports', id: 'missing' } }, 'remind', '', records, timestamp), '关联记录不可用');
assert.equal(JSON.stringify({ tasks, records }), original);
console.log('PASS: batch preview skips, assignment preservation, atomic validation, revisions, recipient routing, cooldown boundary, missing/inactive/unassigned/completed guards, immutable business records.');
