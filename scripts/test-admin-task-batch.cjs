const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    await page.clock.setFixedTime(new Date('2026-09-07T10:00:00Z'));
    const errors = [], requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => requests.push(request.url()));
    await page.goto(process.env.ADMIN_MOCK_URL || 'http://localhost:8092/admin-preview.html');
    const button = name => page.getByRole('button', { name, exact: true });
    const task = name => page.getByRole('article', { name, exact: true });
    const scope = name => page.getByRole('group', { name: '待办范围' }).getByRole('button', { name, exact: true }).click();
    const select = name => page.getByRole('checkbox', { name: `选择${name}`, exact: true }).check();
    await button('打开我的待办').click();
    assert.equal(await page.getByRole('checkbox', { name: '选择确认邀请链接问题恢复', exact: true }).isDisabled(), true);
    await select('跟进轨迹里程反馈');
    assert.equal(await page.getByRole('checkbox', { name: '全选当前可处理任务' }).evaluate(el => el.indeterminate), true);
    await page.getByLabel('搜索通知与待办').fill('轨迹');
    assert.equal(await button('批量分配').isDisabled(), true);
    await page.getByLabel('搜索通知与待办').fill('');
    await select('跟进轨迹里程反馈');
    await button('提醒逾期负责人').click();
    assert.match(await page.locator('.batch-preview').innerText(), /提醒：Kaipa Admin/);
    assert.equal(await button('确认逾期提醒').isDisabled(), true);
    await page.getByLabel('提醒内容').fill('请补充轨迹里程反馈的处理进展');
    page.once('dialog', dialog => dialog.dismiss());
    await button('关闭详情').click();
    assert.equal(await page.getByLabel('提醒内容').inputValue(), '请补充轨迹里程反馈的处理进展');
    await button('确认逾期提醒').click();
    assert.match(await task('跟进轨迹里程反馈').innerText(), /最近提醒/);
    await select('跟进轨迹里程反馈');
    await button('提醒逾期负责人').click();
    assert.match(await page.locator('.batch-preview').innerText(), /24 小时内已提醒/);
    assert.equal(await button('确认逾期提醒').isDisabled(), true);
    await button('返回待办列表').click();
    await page.getByRole('group', { name: '个人工作视图' }).getByRole('button', { name: /^通知中心/ }).click();
    await page.getByLabel('工作项类型').selectOption('逾期提醒');
    assert.equal(await page.locator('.inbox-item').count(), 1);
    await button('关闭详情').click();
    await button('打开我的待办').click();
    await scope('团队全部');
    await select('审核重装徒步装备分享');
    await select('审核山野照片分享');
    await select('核实路线分享广告举报');
    await button('批量分配').click();
    await page.getByLabel('批量负责人').selectOption('A-002');
    assert.match(await page.locator('.batch-preview').innerText(), /负责人未变化/);
    assert.match(await page.locator('.section-head').last().innerText(), /2 项执行，1 项跳过/);
    await page.getByLabel('批量分配说明').fill('统一由小林跟进，保留原定计划');
    await page.screenshot({ path: '/tmp/kaipa-admin-batch-desktop-light.png' });
    await button('确认批量分配').click();
    assert.match(await task('审核重装徒步装备分享').innerText(), /负责人：小林/);
    assert.match(await task('核实路线分享广告举报').innerText(), /负责人：小林/);
    assert.equal(await button('批量分配').isDisabled(), true);
    await task('审核重装徒步装备分享').getByRole('button', { name: '分配与协作' }).click();
    assert.match(await page.locator('.task-events').innerText(), /统一由小林跟进/);
    assert.equal(await page.getByLabel('截止时间（UTC）').inputValue(), '2026-09-07T18:00');
    await button('返回待办列表').click();
    await page.getByRole('checkbox', { name: '全选当前可处理任务' }).check();
    await button('提醒逾期负责人').click();
    assert.match(await page.locator('.batch-preview').innerText(), /尚未逾期/);
    await button('关闭详情').click();
    await button('切换主题').click();
    await button('打开我的待办').click();
    await page.getByRole('checkbox', { name: '全选当前可处理任务' }).check();
    await button('提醒逾期负责人').click();
    await page.screenshot({ path: '/tmp/kaipa-admin-batch-desktop-dark.png' });
    for (const width of [390, 320]) {
      await page.setViewportSize({ width, height: 844 });
      assert.equal(await page.locator('.drawer').evaluate(el => el.scrollWidth === el.clientWidth), true);
      await page.screenshot({ path: `/tmp/kaipa-admin-batch-${width}-dark.png` });
    }
    await button('返回待办列表').click();
    await page.screenshot({ path: '/tmp/kaipa-admin-batch-list-mobile-dark.png' });
    assert.equal(await page.locator('.drawer').evaluate(el => el.scrollWidth === el.clientWidth), true);
    await button('关闭详情').click();
    await button('切换主题').click();
    await button('打开通知中心').click();
    await page.getByRole('group', { name: '个人工作视图' }).getByRole('button', { name: /^我的待办/ }).click();
    await page.screenshot({ path: '/tmp/kaipa-admin-batch-list-mobile-light.png' });
    await button('关闭详情').click();
    await button('重置模拟数据').click();
    await button('确认重置').click();
    await button('打开通知中心').click();
    assert.match(await page.locator('.inbox-heading').innerText(), /3 条未读/);
    await page.getByRole('group', { name: '个人工作视图' }).getByRole('button', { name: /^我的待办/ }).click();
    assert.equal(await page.locator('.task-reminder-time').count(), 0);
    assert.deepEqual(errors, []);
    assert.equal(requests.some(url => /\/rest\/v1|\/auth\/v1|\/functions\/v1/.test(url)), false);
    console.log('PASS: selection/indeterminate/filter reset, batch preview/skips/assignment, dirty guard, reminder delivery/cooldown/history, preserved schedules, reset, desktop/mobile themes, no backend calls.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
