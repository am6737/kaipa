const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, filename);
const { assignedTasks } = require('../src/web/admin/adminInboxModel.ts');
const { updateTask, taskSettings } = require('../src/web/admin/taskCollaborationModel.ts');
const task = assignedTasks.find(task => !task.assignee);
const records = { reports: [{ id: task.target.id, status: '待处理' }], admins: [{ id: 'A-001', name: 'Admin', status: '正常', category: '超级管理员' }, { id: 'A-002', name: 'Ops', status: '正常', category: '运营管理员' }, { id: 'A-003', status: '邀请中' }, { id: 'A-004', status: '正常', category: '只读观察员' }] };
const original = JSON.stringify({ task, records });
const command = { kind: 'update', revision: 0, text: '认领并邀请协作', value: { ...taskSettings(task), assignee: 'A-001', collaborators: ['A-002'] } };
const update = (value, cmd) => updateTask(value, cmd, records, 'A-001', '2026-09-07 12:00', 'event-test');
const claimed = update(task, command);
assert.equal(claimed.revision, 1);
assert.equal(claimed.assignee, 'A-001');
assert.deepEqual(claimed.events[0].recipients, ['Ops']);
assert.equal(JSON.stringify({ task, records }), original);
assert.throws(() => update(claimed, command), /已更新/);
assert.throws(() => update(task, { ...command, text: ' ' }), /说明/);
for (const assignee of ['A-003', 'A-004', 'missing']) assert.throws(() => update(task, { ...command, value: { ...command.value, assignee } }), /正常/);
assert.throws(() => update(task, { ...command, value: { ...command.value, collaborators: ['A-001'] } }), /不能同时/);
assert.throws(() => update(task, { ...command, value: { ...command.value, due: '2026-02-30 12:00' } }), /有效/);
assert.throws(() => update(task, { ...command, value: taskSettings(task) }), /没有变化/);
const transferred = update(claimed, { ...command, revision: 1, value: { ...taskSettings(claimed), assignee: 'A-002', collaborators: ['A-001'] } });
assert.equal(transferred.events.length, 2);
assert.match(transferred.events[1].changes[0], /Admin → Ops/);
const comment = update(transferred, { kind: 'comment', revision: 2, text: '已补充证据' });
assert.equal(comment.events.length, 3);
assert.equal(comment.assignee, 'A-002');
records.reports[0].status = '已处理';
assert.throws(() => update(comment, { ...command, revision: 3 }), /已完成/);
assert.equal(update(comment, { kind: 'comment', revision: 3, text: '归档结论' }).events.length, 4);
records.reports = [];
assert.throws(() => update(comment, { kind: 'comment', revision: 3, text: '留言' }), /不可用/);
console.log('PASS: claim/transfer/collaborators, append-only history, notifications, revision guard, eligibility, deadlines, no-op rejection, completion lock, immutable business records.');
