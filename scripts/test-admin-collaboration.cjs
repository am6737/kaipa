const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    const errors = [], requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => requests.push(request.url()));
    await page.goto(process.env.ADMIN_MOCK_URL || 'http://localhost:8092/admin-preview.html');
    const button = name => page.getByRole('button', { name, exact: true });
    const scope = name => page.getByRole('group', { name: '待办范围' }).getByRole('button', { name, exact: true }).click();
    const task = name => page.getByRole('article', { name, exact: true });
    await button('打开我的待办').click();
    await scope('团队全部');
    assert.equal(await page.locator('.inbox-item').count(), 7);
    await scope('未分配');
    assert.equal(await page.locator('.inbox-item').count(), 1);
    await task('核实路线分享广告举报').getByRole('button', { name: '分配与协作' }).click();
    await page.getByLabel('负责人', { exact: true }).selectOption('A-001');
    assert.equal(await page.getByLabel('负责人', { exact: true }).locator('option[value="A-003"]').evaluate(option => option.disabled), true);
    await page.getByRole('checkbox', { name: /小林/ }).check();
    await page.getByLabel('优先级', { exact: true }).selectOption('高');
    await page.getByLabel('截止时间（UTC）', { exact: true }).fill('2026-09-10T18:00');
    assert.equal(await button('保存分配').isDisabled(), true);
    await page.getByLabel('分配或变更说明').fill('我先核实内容，请小林协助整理证据');
    await button('保存分配').click();
    assert.match(await page.locator('.task-events').innerText(), /未分配 → Kaipa Admin/);
    assert.match(await page.locator('.task-events').innerText(), /模拟通知对象：小林/);
    await page.getByLabel('协作留言').fill('已检查原始分享，等待补充证据。');
    page.once('dialog', dialog => dialog.dismiss());
    await button('关闭详情').click();
    assert.equal(await page.getByLabel('协作留言').inputValue(), '已检查原始分享，等待补充证据。');
    await button('添加留言').click();
    assert.equal(await page.locator('.task-events li').count(), 2);
    await page.getByLabel('负责人', { exact: true }).selectOption('A-002');
    await page.getByRole('checkbox', { name: /Kaipa Admin/ }).check();
    await page.getByLabel('分配或变更说明').fill('转交小林继续处理，我保留协作跟进');
    await button('保存分配').click();
    assert.equal(await page.locator('.task-events li').count(), 3);
    await button('返回待办列表').click();
    assert.equal(await page.locator('.inbox-item').count(), 0);
    await scope('我负责');
    assert.equal(await task('核实路线分享广告举报').count(), 0);
    await scope('我协作');
    assert.equal(await page.locator('.inbox-item').count(), 1);
    assert.match(await task('核实路线分享广告举报').innerText(), /负责人：小林/);
    await task('核实路线分享广告举报').getByRole('button', { name: '分配与协作' }).click();
    assert.equal(await page.getByLabel('负责人', { exact: true }).inputValue(), 'A-002');
    await page.screenshot({ path: '/tmp/kaipa-admin-collaboration-desktop-light.png' });
    await button('查看业务记录').click();
    await page.getByRole('heading', { name: '路线分享包含广告', exact: true }).waitFor();
    assert.match(await page.getByRole('dialog').innerText(), /待处理/);
    await button('结案').click();
    await page.getByLabel('处理原因').fill('已完成核实与处理');
    await button('确认结案').click();
    await button('打开我的待办').click();
    await scope('我协作');
    assert.match(await task('核实路线分享广告举报').innerText(), /已完成/);
    await task('核实路线分享广告举报').getByRole('button', { name: '分配与协作' }).click();
    assert.equal(await page.getByLabel('负责人', { exact: true }).isDisabled(), true);
    await page.getByLabel('协作留言').fill('处理结论已归档。');
    await button('添加留言').click();
    await button('关闭详情').click();
    assert.equal(await page.locator('.inbox-unread-count').innerText(), '3');
    await button('切换主题').click();
    await button('打开我的待办').click();
    await scope('团队全部');
    await task('核实路线分享广告举报').getByRole('button', { name: '分配与协作' }).click();
    await page.screenshot({ path: '/tmp/kaipa-admin-collaboration-desktop-dark.png' });
    for (const width of [390, 320]) {
      await page.setViewportSize({ width, height: 844 });
      await page.locator('.drawer').evaluate(el => el.scrollTo({ top: 0 }));
      assert.equal(await page.locator('.drawer').evaluate(el => el.scrollWidth === el.clientWidth), true);
      await page.screenshot({ path: `/tmp/kaipa-admin-collaboration-${width}-dark.png` });
    }
    await button('关闭详情').click();
    await button('切换主题').click();
    await button('打开通知中心').click();
    await page.getByRole('group', { name: '个人工作视图' }).getByRole('button', { name: /^我的待办/ }).click();
    await page.screenshot({ path: '/tmp/kaipa-admin-collaboration-mobile-light.png' });
    await button('关闭详情').click();
    await button('重置模拟数据').click();
    await button('确认重置').click();
    await button('打开通知中心').click();
    await page.getByRole('group', { name: '个人工作视图' }).getByRole('button', { name: /^我的待办/ }).click();
    await scope('未分配');
    assert.equal(await page.locator('.inbox-item').count(), 1);
    await task('核实路线分享广告举报').getByRole('button', { name: '分配与协作' }).click();
    assert.equal(await page.locator('.task-events li').count(), 0);
    assert.deepEqual(errors, []);
    assert.equal(requests.some(url => /\/rest\/v1|\/auth\/v1|\/functions\/v1/.test(url)), false);
    console.log('PASS: team/unassigned/personal/collaborator scopes, claim, transfer, collaborator eligibility, required reason, comments, dirty guard, business completion lock, recipient isolation, reset, responsive themes, no backend calls.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
